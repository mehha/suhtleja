"""Writes src/utilities/grammar/verbForms.ts: the present stem and da-infinitive of every verb the
board conjugates (see docs/rules/project/boards.md, "Word forms").

The verbs are the picture bank's (scripts/pildipank/sonavara.csv: every word, or last word of a
phrase, in -ma that Vabamorf conjugates) and verbs.txt. Vabamorf (EstNLTK) makes the forms. It is
only needed here, on a developer's machine; the app reads the generated file.

    python3 -m venv /tmp/estnltk && /tmp/estnltk/bin/pip install estnltk==1.7.5
    /tmp/estnltk/bin/python scripts/grammar/generate-verbs.py

A verb with two forms of the same kind (Vabamorf knows "jooksta" and "joosta") stops the script
until PREFERRED names the one the board says.
"""

import csv
import re
import sys
from pathlib import Path

from estnltk.vabamorf.morf import synthesize

ROOT = Path(__file__).resolve().parents[2]
BANK = ROOT / 'scripts/pildipank/sonavara.csv'
EXTRA = ROOT / 'scripts/grammar/verbs.txt'
OUT = ROOT / 'src/utilities/grammar/verbForms.ts'

# The form the board says where Vabamorf gives two: (verb, form) -> word. The 1st person singular
# sets the stem; a person form with two variants then takes the one on that stem ("lähe" gives
# "läheme", not "lähme").
PREFERRED: dict[tuple[str, str], str] = {
    ('jooksma', 'da'): 'joosta',
    ('lõppema', 'n'): 'lõpen',
    ('mõtlema', 'da'): 'mõelda',
    ('sulgema', 'n'): 'sulen',
    ('sügelema', 'da'): 'sügeleda',
    ('ütlema', 'da'): 'öelda',
}

# The present forms besides the 1st person singular, with the ending each adds to the stem.
PERSON_ENDINGS = {'d': 'd', 'b': 'b', 'me': 'me', 'te': 'te', 'vad': 'vad'}

MA = re.compile(r'^[a-zäöüõšž]{2,}ma$')


def bank_verbs() -> tuple[set[str], list[str]]:
    verbs: set[str] = set()
    skipped: list[str] = []
    with BANK.open(encoding='utf-8') as f:
        for row in csv.DictReader(f):
            last = row['sõna'].strip().lower().split(' ')[-1]
            if not MA.match(last):
                continue
            if synthesize(last, 'n', 'V'):
                verbs.add(last)
            else:
                skipped.append(row['sõna'])
    return verbs, skipped


def extra_verbs() -> set[str]:
    words = set()
    for line in EXTRA.read_text(encoding='utf-8').splitlines():
        word = line.strip()
        if word and not word.startswith('#'):
            words.add(word)
    return words


def one(verb: str, form: str, problems: list[str], on_stem: str | None = None) -> str:
    found = synthesize(verb, form, 'V')
    if on_stem and len(found) > 1 and on_stem in found:
        return on_stem
    if (verb, form) in PREFERRED:
        preferred = PREFERRED[(verb, form)]
        if preferred not in found:
            problems.append(f'{verb} {form}: PREFERRED {preferred!r} is not one of {found}')
        return preferred
    if len(found) != 1:
        problems.append(f'{verb} {form}: {found or "no form"}')
        return found[0] if found else ''
    return found[0]


def main() -> None:
    bank, skipped = bank_verbs()
    extra = extra_verbs()
    problems: list[str] = []
    rows: list[tuple[str, str, str, dict[str, str]]] = []

    for verb in sorted(bank | extra):
        first = one(verb, 'n', problems)
        if not first.endswith('n'):
            problems.append(f'{verb} n: {first!r} does not end in -n')
            continue
        stem = first[:-1]
        irregular = {}
        for form, ending in PERSON_ENDINGS.items():
            word = one(verb, form, problems, on_stem=stem + ending)
            if word != stem + ending:
                irregular[form] = word
        rows.append((verb, stem, one(verb, 'da', problems), irregular))

    if problems:
        print('Fix these (PREFERRED or the lists):', *problems, sep='\n  ', file=sys.stderr)
        sys.exit(1)

    lines = [
        '// Generated by scripts/grammar/generate-verbs.py with Vabamorf (EstNLTK). Edit the word lists',
        '// there (scripts/grammar/verbs.txt, scripts/pildipank/sonavara.csv) and rerun it; don\'t edit',
        '// this file.',
        '//',
        '// Each verb: its present stem (the forms are the stem plus -n, -d, -b, -me, -te, -vad, and the',
        '// stem alone after "ei") and its da-infinitive.',
        'export const VERB_FORMS: Record<string, readonly [present: string, da: string]> = {',
    ]
    for verb, stem, da, _ in rows:
        lines.append(f"  {key(verb)}: ['{stem}', '{da}'],")
    lines.append('}')
    lines.append('')
    lines.append('// Present forms that are not the stem plus the ending, by Vabamorf\'s form code.')
    lines.append('export const IRREGULAR_PRESENT: Record<string, Partial<Record<\'d\' | \'b\' | \'me\' | \'te\' | \'vad\', string>>> = {')
    for verb, _, _, irregular in rows:
        if irregular:
            forms = ', '.join(f"{form}: '{word}'" for form, word in irregular.items())
            lines.append(f'  {key(verb)}: {{ {forms} }},')
    lines.append('}')
    lines.append('')

    OUT.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{len(rows)} verbs ({len(bank)} from the picture bank) -> {OUT.relative_to(ROOT)}')
    if skipped:
        print('Bank words in -ma that are not verbs:', ', '.join(skipped))


def key(word: str) -> str:
    return word if re.fullmatch(r'[a-zäöüõšž]+', word) else f"'{word}'"


if __name__ == '__main__':
    main()
